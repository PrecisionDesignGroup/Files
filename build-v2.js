/* Builds the V2 site (v2/v2.css, v2/v2.js, v2/v2-boot.js) from v2/src/.
   Images and 3D files live in v2/assets/ and are loaded from jsDelivr pinned to ASSETS_SHA.
   When you change assets: commit them, put that commit's hash in ASSETS_SHA, run: node build-v2.js */
const fs=require("fs");
const ASSETS_SHA="d7c5345ded626bb7852bfe9ee81d4050a192c6ef";
const BASE=`https://cdn.jsdelivr.net/gh/PrecisionDesignGroup/Files@${ASSETS_SHA}/v2/assets/`;
const src=f=>fs.readFileSync("v2/src/"+f,"utf8");
const html=src("index.html");
const cut=(s,a,b)=>{const i=s.indexOf(a),j=s.indexOf(b,i+a.length);if(i<0||j<0)throw new Error("missing "+a);return s.slice(i+a.length,j)};
const rw=s=>s.replace(/(["'`(\s,])((?:art|logos)\/)/g,(m,p,d)=>p+BASE+d);
let css=cut(html,"<style>","</style>");
let body=html.slice(html.indexOf("</style>")+8,html.indexOf("<script>")).trim();
let main=cut(html,"<script>","</script>");
let gm=src("gm.js").replace('const ASSETS="gm/"',`const ASSETS="${BASE}gm/"`);
if(!gm.includes(BASE+"gm/"))throw new Error("gm ASSETS not rewritten");
const parts=[["main",main],["gm.js",gm],["svcui.js",src("svcui.js")],["svform.js",src("svform.js")],["live.js",src("live.js")]];
const js="/* v2.js — generated by build-v2.js from v2/src. Edit those files, not this one. */\n"+parts.map(([n,s])=>`/* ===== ${n} ===== */\ntry{\n${rw(s)}\n}catch(e){console.error("${n}",e)}`).join("\n")+"\n";
fs.writeFileSync("v2/v2.css",rw(css));
fs.writeFileSync("v2/v2.js",js);
const FONTS="https://fonts.googleapis.com/css2?family=Big+Shoulders+Display:wght@700;900&family=Instrument+Sans:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500&display=swap";
const boot=`/* v2-boot.js — generated by build-v2.js. Loaded from the page's head code; draws the V2 site and stops the rest of the
   Webflow page from loading (so the old site's embeds never run). Remove the head code to get the old site back. */
(function(){
var B=(document.currentScript&&document.currentScript.src||"").replace(/v2-boot\\.js.*$/,"");
for(var i=0,l=document.querySelectorAll('link[rel="stylesheet"]');i<l.length;i++)if(/website-files\\.com|webflow\\./.test(l[i].href))l[i].disabled=true;
var vp=document.querySelector('meta[name="viewport"]');if(vp)vp.setAttribute("content","width=device-width, initial-scale=1, viewport-fit=cover");
document.documentElement.classList.add("pd2");
var BODY=${JSON.stringify(rw(body)).replace(/<\/script/gi,"<\\/script")};
document.write('<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link rel="stylesheet" href="${FONTS}"><link rel="stylesheet" href="'+B+'v2.css">'+BODY+'<script src="'+B+'v2.js" charset="utf-8"><\\/script><plaintext style="display:none">');
})();
`;
fs.writeFileSync("v2/v2-boot.js",boot);
console.log("v2.css",fs.statSync("v2/v2.css").size,"v2.js",fs.statSync("v2/v2.js").size,"v2-boot.js",fs.statSync("v2/v2-boot.js").size);
